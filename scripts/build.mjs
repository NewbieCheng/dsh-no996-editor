import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const outputIndex = process.argv.indexOf('--outfile');
if (outputIndex !== -1 && !process.argv[outputIndex + 1]) throw new Error('--outfile needs a path');
const outfile = outputIndex === -1 ? 'client.js' : process.argv[outputIndex + 1];
const result = await build({
  absWorkingDir: root,
  entryPoints: ['src/studio/studio-entry.js'],
  outfile,
  bundle: true,
  write: false,
  format: 'iife',
  platform: 'browser',
  target: 'es2022',
  legalComments: 'inline',
  banner: { js: '/* Generated by scripts/build.mjs. OpenFilm portions: MIT, see vendor/LICENSE. */' },
});
const dest = resolve(root, outfile);
mkdirSync(dirname(dest), { recursive: true });
writeFileSync(dest, result.outputFiles[0].contents);
